"""Size report of H2 installs against a baseline install (TEST-05).

For each install dir, compares libh2kernel.a (with the objects that changed),
libh2.a and bin/booter against a baseline install: --baseline DIR ({archv} is
replaced by the install's ARCHV), or with --pkw the pkw h2 package
v<ARCHV>_latest.  ARCHV and variant come from each install's ver file.
A missing baseline is an error.

Usage:
    size_report.py [--output F] [--print] (--baseline DIR | --pkw [--pkw-version V]) INSTALL...
    size_report.py --baseline /path/h2/v{archv}_latest artifacts/v*/opt/install
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import section_size  # noqa: E402

COLS = section_size.COLS
KERNEL = "lib/libh2kernel.a"
FILES = (KERNEL, "lib/libh2.a", "bin/booter")
MAX_OBJS = 12


def read_ver(install):
	"""(archv, variant, commit) from <install>/ver."""
	archv, variant, commit = "?", "?", "unknown"
	try:
		with open(os.path.join(install, "ver")) as f:
			for i, line in enumerate(f):
				w = line.split()
				if i == 0 and len(w) >= 2:
					archv, variant = w[0].lstrip("v"), w[1]
				elif w[:1] == ["sha_short"] and len(w) > 1:
					commit = w[1].replace("0x", "")
	except OSError:
		pass
	return archv, variant, commit


def pkw_install(version):
	"""Q6_RTOS_INSTALL of pkw package h2 at version, or None."""
	env = dict(os.environ, PKW_h2=version)
	try:
		out = subprocess.run(["pkw", "--env", "h2"], env=env, capture_output=True,
				     text=True, timeout=120).stdout
	except (OSError, subprocess.TimeoutExpired):
		return None
	m = re.search(r'Q6_RTOS_INSTALL="([^"]*)"', out)
	return m.group(1) if m else None


def measure(install):
	"""{file: {member: {col: bytes}}} for FILES under install; missing files omitted."""
	paths = {os.path.join(install, f): f for f in FILES}
	return {paths[p]: s for p, s in section_size.measure(list(paths)).items()}


def tot(members):
	return sum(section_size.total(members).values()) if members is not None else None


def fmt(v):
	return "missing" if v is None else str(v)


def fmt_delta(cur, base):
	if cur is None or base is None:
		return "-"
	d = cur - base
	if d == 0:
		return "0"
	pct = " (%+.1f%%)" % (100.0 * d / base) if base else ""
	return "%+d%s" % (d, pct)


def changed_objects(cur, base):
	"""'obj +N' for archive members whose total changed, largest first."""
	ch = []
	for m in set(cur) | set(base):
		c = sum(cur[m].values()) if m in cur else None
		b = sum(base[m].values()) if m in base else None
		if c == b:
			continue
		tag = " (new)" if b is None else " (gone)" if c is None else ""
		d = (c or 0) - (b or 0)
		ch.append((abs(d), "%s %+d%s" % (m, d, tag)))
	ch.sort(key=lambda x: (-x[0], x[1]))
	s = ", ".join(x[1] for x in ch[:MAX_OBJS])
	if len(ch) > MAX_OBJS:
		s += ", %d more" % (len(ch) - MAX_OBJS)
	return s or "none"


def report(args):
	rows = []
	for install in args.installs:
		if not os.path.exists(os.path.join(install, "ver")):
			print("size_report: %s is not an install (no ver file)" % install, file=sys.stderr)
			return 1
		archv, variant, commit = read_ver(install)
		if args.pkw:
			bdir = pkw_install(args.pkw_version.format(archv=archv))
		else:
			bdir = args.baseline.format(archv=archv)
		if not bdir or not os.path.isdir(bdir):
			print("size_report: no baseline install for v%s (%s)" % (archv, bdir or "pkw"),
			      file=sys.stderr)
			return 1
		rows.append({"name": "v%s/%s" % (archv, variant), "commit": commit,
			     "cur": measure(install),
			     "bcommit": read_ver(bdir)[2], "base": measure(bdir)})

	L = ["# H2 size report", "",
	     "Bytes; total = text + rodata + data + bss.  Baseline: %s; its commit "
	     "is in the baseline column." % (
		     "PKW_h2=" + args.pkw_version if args.pkw else args.baseline).replace(
			     "{archv}", "<ARCHV>"),
	     "Generated by scripts/size_report.py.", "",
	     "## Totals (delta vs. baseline)", ""]
	hdr = ["variant", "commit", "baseline"]
	for f in FILES:
		hdr += [os.path.basename(f), "delta"]
	L.append("| " + " | ".join(hdr) + " |")
	L.append("|---|---|---" + "|---:" * (len(hdr) - 3) + "|")
	for r in rows:
		row = [r["name"], r["commit"], r["bcommit"]]
		for f in FILES:
			c, b = tot(r["cur"].get(f)), tot(r["base"].get(f))
			row += [fmt(c), fmt_delta(c, b)]
		L.append("| " + " | ".join(row) + " |")

	L += ["", "## Kernel: libh2kernel.a", "",
	      "| variant | text | rodata | data | bss | total | delta | changed objects |",
	      "|---|---:|---:|---:|---:|---:|---:|---|"]
	for r in rows:
		k, bk = r["cur"].get(KERNEL), r["base"].get(KERNEL)
		if k is None:
			L.append("| %s | missing |||||||" % r["name"])
			continue
		s = section_size.total(k)
		L.append("| %s | %s | %d | %s | %s |" % (
			r["name"], " | ".join(str(s[c]) for c in COLS), tot(k),
			fmt_delta(tot(k), tot(bk)), changed_objects(k, bk) if bk else "-"))

	text = "\n".join(L) + "\n"
	if args.output:
		with open(args.output, "w") as f:
			f.write(text)
	if args.print or not args.output:
		sys.stdout.write(text)
	return 0


def main():
	ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	ap.add_argument("installs", nargs="+", metavar="INSTALL", help="install dir with a ver file")
	base = ap.add_mutually_exclusive_group(required=True)
	base.add_argument("--baseline", help="baseline install dir; {archv} is substituted")
	base.add_argument("--pkw", action="store_true", help="baseline from pkw (PKW_h2)")
	ap.add_argument("--pkw-version", default="v{archv}_latest",
			help="PKW_h2 version with --pkw; {archv} is substituted (default %(default)s)")
	ap.add_argument("--output", help="markdown file (default: stdout)")
	ap.add_argument("--print", action="store_true", help="also print to stdout")
	return report(ap.parse_args())


if __name__ == "__main__":
	sys.exit(main())
